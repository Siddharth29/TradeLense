"""Strict trade JSON schemas for expert signals and judge decisions."""

from typing import Literal, Optional, Dict, Any, List
from pydantic import BaseModel, confloat, conint, model_validator


class BacktestPrediction(BaseModel, extra="forbid"):
    """Canonical prediction type for backtest flow.
    
    This is the single source of truth for prediction data structure
    used throughout the system: frontend → backend → GPT API → 5m monitoring.
    
    Field names are canonical and consistent:
    - entry: Entry price (not entry_price, level, etc.)
    - stop: Stop loss price (not stoploss, stop_loss, sl, etc.)
    - target: Target price (not take_profit_1, tp, etc.)
    - direction: Trade direction (long/short)
    - pattern: Trading pattern name
    - confidence: Confidence level (high/medium/low)
    - status: Prediction status (waiting/monitoring/etc.)
    """
    direction: Literal["long", "short"]
    entry: float  # Entry price
    stop: float   # Stop loss price
    target: float # Target price
    pattern: str  # Trading pattern name
    confidence: Literal["high", "medium", "low"]
    status: Literal["waiting", "monitoring", "triggered", "expired"] = "waiting"


class MultiExpertSignal(BaseModel, extra="ignore"):
    """Schema for multi-expert trading signals with TTL and validation constraints.

    Uses extra="ignore" so LLM-generated extra fields (e.g. "context") are
    silently dropped instead of rejecting the entire proposal.

    For flat signals, entry/stop/target can be None to indicate no trade.
    For buy/sell signals, all price fields are required.
    """
    signal: Literal["buy", "sell", "flat"]
    entry: Optional[float] = None
    stop: Optional[float] = None
    target: Optional[float] = None
    ttl_minutes: Literal[90, 180, 240]
    confidence: confloat(ge=0, le=1)
    rationale: Optional[str] = None
    setup: Optional[Dict[str, Any]] = None
    # Deprecated V1 fields — accepted but ignored
    active_window_c5: Optional[int] = None
    active_window_c15: Optional[int] = None

    @model_validator(mode="after")
    def validate_price_fields(self):
        if self.signal != "flat":
            if self.entry is None or self.stop is None or self.target is None:
                raise ValueError(
                    f"Non-flat signal '{self.signal}' requires entry, stop, and target. "
                    f"Got: entry={self.entry}, stop={self.stop}, target={self.target}"
                )
        return self


class DynamicConfig(BaseModel, extra="forbid"):
    """Dynamic configuration recommendations from AI judge.
    
    This model represents the AI's recommendations for dynamic TTL and candle counts
    based on current market conditions. Used to optimize the next trading cycle.
    """
    ttl_minutes: conint(ge=30, le=180)  # Dynamic TTL based on market volatility
    candles_5m_count: conint(ge=50, le=200)  # Dynamic 5m candle count (minimum relaxed to 20)
    candles_15m_count: conint(ge=20, le=100)  # Dynamic 15m candle count based on trend strength
    reasoning: str  # AI's reasoning for the parameter choices
    market_volatility: Literal["low", "medium", "high"]  # Market volatility assessment
    trend_strength: Literal["weak", "moderate", "strong"]  # Trend strength assessment


class UnifiedExpertResponse(BaseModel, extra="forbid"):
    """Schema for unified expert response.

    1. proposals: 1-2 trading proposals
    2. candel_required_for_judge: How many 5m candles judge should receive (10-30)
    """
    proposals: List[MultiExpertSignal]
    candel_required_for_judge: conint(ge=10, le=30)

    @model_validator(mode="after")
    def validate_proposal_count(self):
        if not (1 <= len(self.proposals) <= 2):
            raise ValueError(
                f"Unified Expert must return 1-2 proposals, got {len(self.proposals)}."
            )
        return self


class CodeSniperSignal(BaseModel, extra="forbid"):
    """Strict schema for code sniper judge-generated Python trading code.
    
    This model represents the output when the judge generates Python trading code
    instead of JSON signals. The code will be executed in a sandbox environment
    with fixed input/output contracts.
    """
    code: str  # Python trading code generated by the judge
    metadata: Dict[str, Any]  # Additional metadata (confidence, rationale, etc.)
    ttl_minutes: Literal[90, 180, 240]  # Time to live; MUST match config.TTL_MINUTES_ALLOWED
    #   (pinned by tests/test_edge_horizon_2026_08_06.py — a drift here is an LP-09-class parse failure)
    confidence: confloat(ge=0, le=1)  # Confidence in the generated code
    input_schema: Optional[Dict[str, Any]] = None  # Optional: Schema for input data
    output_schema: Optional[Dict[str, Any]] = None  # Optional: Schema for expected output
    dynamic_config: Optional[DynamicConfig] = None  # Optional dynamic configuration recommendations


